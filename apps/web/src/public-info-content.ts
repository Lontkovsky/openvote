export const publicInfoPageSlugs = publicInfoPages.map(page => page.slug);

export function publicInfoPage(slug: string): PublicInfoPage {
  const page = publicInfoPages.find(candidate => candidate.slug === slug);
  if (page === undefined) throw new Error('PUBLIC_INFO_PAGE_UNKNOWN');
  return page;
}

export function publicInfoSlugFromPath(pathname: string): PublicInfoPage['slug'] {
  const match = /^\/(about|how-it-works|methodology|privacy|faq)\/?$/u.exec(pathname);
  const slug = match?.[1];
  if (slug === 'about' || slug === 'how-it-works' || slug === 'methodology' || slug === 'privacy' || slug === 'faq') return slug;
  throw new Error('PUBLIC_INFO_ROUTE_UNKNOWN');
}
